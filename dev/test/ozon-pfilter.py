"""Озон: таблица «Товары» — отбор по схеме (FBO / realFBS) и по тому, чей товар (мой / Тани). 26.11.2026."""
import asyncio, os, tempfile, importlib.util
from playwright.async_api import async_playwright
spec=importlib.util.spec_from_file_location('oz', os.path.join(os.path.dirname(__file__),'ozon.py')); oz=importlib.util.module_from_spec(spec); spec.loader.exec_module(oz)
fails=[]
def ok(c,m): print(('✓ ' if c else '✗ ')+m); (None if c else fails.append(m))
async def main():
    ph=os.environ.get('PH')=='1'; vw=(390,844) if ph else (1300,900)
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path=os.environ.get("BROWSER_EXECUTABLE_PATH")); pg=await b.new_page(viewport={'width':vw[0],'height':vw[1]}); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.route('**/xlsx.full.min.js', lambda r: r.fulfill(path=os.environ['XLSXJS']))
        await pg.goto(oz.BASE+'/page'); await pg.evaluate("try{indexedDB.deleteDatabase('frudom-ozon'); localStorage.removeItem('frudom-oz-ui')}catch(e){}"); await pg.reload()
        await pg.click('#fd-who [data-who="Даниил"]'); await pg.fill('#fd-pass','1111'); await pg.click('#fd-enter'); await pg.wait_for_timeout(2500)
        await pg.evaluate("(()=>{const b=document.querySelector('nav.tabs button[data-tab=ozon]'); if(b) b.click(); else goTab('ozon');})()"); await pg.wait_for_timeout(800)
        f=tempfile.mktemp(suffix='.xlsx'); oz.mk_xlsx(f); await pg.set_input_files('#oz-file', f); await pg.wait_for_timeout(1500)
        L=await pg.evaluate("__oz.calc().L.map(p=>({k:p.key,s:Object.keys(p.sch),t:!!p.tanya}))")
        nF=len([x for x in L if 'FBO' in x['s']]); nR=len([x for x in L if 'RFBS' in x['s']])
        rows=lambda: pg.locator('#oz .ozprods [data-ozp]').count()
        ok(await rows()==len(L), f'сначала все товары ({len(L)})')
        await pg.click('#oz [data-ozps="FBO"]'); await pg.wait_for_timeout(400)
        ok(await rows()==nF, f'FBO — только товары со склада Озона ({nF})')
        ok('Показано' in await pg.inner_text('#oz .ozpsum'), 'строка-итог по отобранным')
        await pg.click('#oz [data-ozps="RFBS"]'); await pg.wait_for_timeout(400)
        ok(await rows()==nR, f'realFBS ({nR})')
        await pg.click('#oz [data-ozps="all"]'); await pg.wait_for_timeout(300)
        ok(await pg.locator('#oz [data-ozpw]').count()==0, 'пока товара Тани нет — выбора «Чьи» нет')
        await pg.click('#oz [data-oz="own"]'); await pg.wait_for_timeout(500)
        await pg.click('#fd-dcard [data-ozowna="смесь"] [data-ozown="t"]'); await pg.wait_for_timeout(400); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(500)
        L=await pg.evaluate("__oz.calc().L.map(p=>({k:p.key,s:Object.keys(p.sch),t:!!p.tanya}))"); nT=len([x for x in L if x['t']])
        await pg.click('#oz [data-ozpw="t"]'); await pg.wait_for_timeout(400)
        ok(nT>0 and await rows()==nT, f'«Тани» — только её товары ({nT})')
        await pg.click('#oz [data-ozpw="me"]'); await pg.wait_for_timeout(400)
        ok(await rows()==len(L)-nT, f'«Мои» — без товара Тани ({len(L)-nT})')
        await pg.click('#oz [data-ozps="FBO"]'); await pg.wait_for_timeout(400)
        want=len([x for x in L if not x['t'] and 'FBO' in x['s']])
        ok(await rows()==want, f'«Мои» + FBO вместе ({want})')
        await pg.reload(); await pg.wait_for_timeout(2500)
        await pg.evaluate("(()=>{const b=document.querySelector('nav.tabs button[data-tab=ozon]'); if(b) b.click();})()"); await pg.wait_for_timeout(1200)
        ok(await pg.locator('#oz [data-ozps="FBO"].on').count()==1 and await pg.locator('#oz [data-ozpw="me"].on').count()==1, 'выбор запоминается')
        await pg.click('#oz [data-ozpclr]'); await pg.wait_for_timeout(400)
        ok(await rows()==len(L), '«Показать все ×» снимает отбор')
        sw=await pg.evaluate("document.documentElement.scrollWidth"); ok(sw<=vw[0]+1, f'нет прокрутки вбок ({sw})')
        ok(not errs, f'без ошибок {errs[:2]}')
        await b.close()
    print('ошибок:', len(fails)); raise SystemExit(1 if fails else 0)
asyncio.run(main())
